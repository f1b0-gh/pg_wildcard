"""End-to-end test of wildcard_fdw and the planner rewrite.

Real PostgreSQL (extension installed with `cargo pgrx install`) talks over HTTP
to ClickHouse (chDB behind ch_http_shim.py). Checks:
  1. wc_* results through the FDW equal local evaluation, for plain tables
     (view expressions) and tables with materialized view columns;
  2. filters are applied in ClickHouse (EXPLAIN shows the SQL; no rows removed locally);
  3. the planner rewrite turns wc_match(.., 'raw') into LIKE;
  4. lake pruning: EXPLAIN shows "Lake files: k of N", results equal the unpruned
     table, and a truncated non-candidate file does not break the pruned query.

Run as a non-root user:  python3 tests/fdw/run.py <path to wc-lake binary>
"""
import json, os, random, shutil, signal, subprocess, sys, tempfile, time, urllib.request
import pyarrow as pa, pyarrow.parquet as pq

WC_LAKE = os.path.abspath(sys.argv[1])
PGBIN = subprocess.run(["pg_config", "--bindir"], capture_output=True, text=True).stdout.strip()
HERE = os.path.dirname(os.path.abspath(__file__))
# Private, short path for PostgreSQL's Unix socket; do not recreate the retired
# shared /tmp/pg_wildcard workspace. mkdtemp creates this directory atomically.
work = tempfile.mkdtemp(prefix="wc-fdw-", dir="/tmp")
PGPORT, CHPORT = "15432", "18123"
procs = []

def sh(*a, **kw):
    r = subprocess.run(a, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        raise subprocess.CalledProcessError(r.returncode, a[:1], r.stdout, r.stderr.strip()[-600:])
    return r.stdout

def ch(sql):
    req = urllib.request.Request(f"http://127.0.0.1:{CHPORT}/?default_format=TabSeparated", data=sql.encode(), method="POST", headers={"Authorization": "Bearer fdw-test-token"})
    with urllib.request.urlopen(req) as r:
        return r.read().decode()

def psql(sql):
    return sh(f"{PGBIN}/psql", "-h", work, "-p", PGPORT, "-d", "postgres", "-X", "-q", "-A", "-t", "-v", "ON_ERROR_STOP=1", "-c", sql)

failures = 0
def check(cond, msg):
    global failures
    print(("ok   " if cond else "FAIL ") + msg)
    failures += 0 if cond else 1

try:
    # ---- ClickHouse (chDB shim), run from the work dir so file() can read ./lake
    procs.append(subprocess.Popen([sys.executable, os.path.join(HERE, "ch_http_shim.py"), "--port", CHPORT], cwd=work))
    # ---- Postgres
    sh(f"{PGBIN}/initdb", "-D", f"{work}/pg", "-A", "trust", "-U", os.environ.get("USER", "dev"))
    sh(f"{PGBIN}/pg_ctl", "-D", f"{work}/pg", "-l", f"{work}/pg.log", "-o", f"-p {PGPORT} -k {work} -c listen_addresses=''", "-w", "start")
    for _ in range(50):
        try:
            ch("SELECT 1"); break
        except Exception:
            time.sleep(0.2)

    psql("CREATE EXTENSION pg_wildcard")
    for regression in ["planner_predicates.sql", "planner_identity.sql"]:
        with open(os.path.join(HERE, regression)) as source:
            psql(source.read())
        check(True, f"planner regression: {regression}")
    rnd = random.Random(11)
    base = ["https://login.evil.com/wp-admin/setup.php", "http://LOGIN.EVIL.COM.:8080/%77p-ADMIN/x.PHP?a=1",
            "https://user:pass@sub.evil.com:443/path", "https://evil.com.attacker.net/", "GET /%2e%2e/%2E%2E/etc/passwd",
            "C:\\Windows\\PowerShell.EXE -EncodedCommand SQBFAFgA", "Mozilla/5.0 (compatible; sqlmap/1.7)", "aéb", "line1\nline2", "a'b\tc\\d"]
    base += ["abc", "abcd", r"a\bc", "a%b", "a_b", "élan"]
    hosts = ["good.example", "shop.example", "cdn.example", "api.example"]
    paths = ["/", "/index.html", "/search?q=x", "/img/a.png", "/static/app.js", "/wp-login.php"]
    urls = base + [f"https://{rnd.choice(hosts)}{rnd.choice(paths)}" for _ in range(2000)]

    # ClickHouse table + materialized view columns generated by pg_wildcard itself
    ch("CREATE DATABASE IF NOT EXISTS d")
    ch("CREATE TABLE d.http (id UInt64, ts DateTime64(6, 'UTC'), url String) ENGINE = MergeTree ORDER BY id")
    ddl = psql("SELECT string_agg(s, E'\\n') FROM wc_ch_view_columns_ddl('d.http', 'url', 'lower,decoded,revdomain') s").strip().split("\n")
    for stmt in ddl:
        ch(stmt)
    values = ", ".join(f"({i}, '2026-11-0{1 + i % 9} 10:00:00', unhex('{u.encode().hex()}'))" for i, u in enumerate(urls))
    ch(f"INSERT INTO d.http (id, ts, url) VALUES {values}")

    psql(f"CREATE SERVER ch FOREIGN DATA WRAPPER wildcard_fdw OPTIONS (url 'http://127.0.0.1:{CHPORT}', database 'd')")
    psql("CREATE USER MAPPING FOR CURRENT_USER SERVER ch OPTIONS (bearer_token 'fdw-test-token')")
    psql("CREATE FOREIGN TABLE http_plain (id bigint, ts timestamp, url text) SERVER ch OPTIONS (table 'd.http')")
    psql("CREATE FOREIGN TABLE http_mat (id bigint, ts timestamp, url text, url_lower text, url_decoded text, url_revdomain text) "
         "SERVER ch OPTIONS (table 'd.http', materialized_views 'true')")
    psql("CREATE FOREIGN TABLE http_candidate (id bigint, ts timestamp, url text) SERVER ch OPTIONS (table 'd.http', candidate_columns 'url')")
    psql("CREATE TABLE http_local AS SELECT id, ts, url FROM http_plain")
    n = int(psql("SELECT count(*) FROM http_local"))
    check(n == len(urls), f"FDW reads all {len(urls)} rows (got {n}), including tabs, newlines, quotes, backslashes")
    same = psql("SELECT count(*) FROM http_local l JOIN unnest(ARRAY[%s]) WITH ORDINALITY u(v, o) ON l.id = u.o - 1 AND l.url = u.v" %
                ",".join("'" + u.replace("'", "''") + "'" for u in urls))
    check(int(same) == len(urls), "every value round-trips byte for byte")

    cases = [("wc_match(url, '*/wp-admin/*.php', 'decoded')"), ("wc_like(url, 'com.evil.%', 'revdomain')"),
             ("wc_match(url, '*passwd', 'raw')"), ("wc_regex(url, 'powershell(\\.exe)?\\s+-e', true, 'lower')"),
             ("wc_match(url, 'a?b', 'raw')"), ("wc_regex(url, 'line1.line2')"), ("wc_match(url, '*\\\\d', 'raw')"),
             ("wc_like(url, '%.php', 'decoded') AND ts >= '2026-11-03'"), ("wc_match(url, '*sqlmap*', 'lower') OR id = 3"),
             ("url LIKE '%/static/%' AND id < 500"),
             (r"url LIKE E'a\\bc'"), (r"url NOT LIKE E'a\\bc'"),
             (r"url LIKE E'a\\%b'"), (r"url LIKE E'a\\_b'")]
    for c in cases:
        local = psql(f"SELECT coalesce(string_agg(id::text, ',' ORDER BY id), '') FROM http_local WHERE {c}")
        for t in ["http_plain", "http_mat"]:
            remote = psql(f"SELECT coalesce(string_agg(id::text, ',' ORDER BY id), '') FROM {t} WHERE {c}")
            plan = psql(f"EXPLAIN (ANALYZE, VERBOSE, COSTS OFF, TIMING OFF, SUMMARY OFF) SELECT id FROM {t} WHERE {c}")
            removed = [l for l in plan.split("\n") if "Rows Removed by Filter" in l]
            pushed = "ClickHouse SQL" in plan and " WHERE " in plan.split("ClickHouse SQL")[1]
            check(remote == local and pushed and not removed,
                  f"{t:10} {c[:60]:60} rows={len(local.split(',')) if local else 0} pushed={pushed} local-filtered={bool(removed)}")
    for style in ["ISO, MDY", "SQL, MDY", "SQL, DMY", "German, DMY"]:
        settings = f"SET DateStyle = '{style}'; SET TimeZone = 'America/New_York'; "
        where = "ts >= TIMESTAMP '2026-11-05 10:00:00.000001'"
        local = psql(settings + f"SELECT array_agg(id ORDER BY id) FROM http_local WHERE {where}")
        remote = psql(settings + f"SELECT array_agg(id ORDER BY id) FROM http_plain WHERE {where}")
        check(local == remote, f"timestamp filter preserves microseconds under {style}")
    plan = psql("EXPLAIN (VERBOSE, COSTS OFF) SELECT id FROM http_mat WHERE wc_match(url, '*/wp-admin/*', 'decoded')")
    check("url_decoded" in plan, "materialized table: rewrite + pushdown target the url_decoded column")
    plan = psql("EXPLAIN (COSTS OFF) SELECT id FROM http_local WHERE wc_match(url, '*evil.com*', 'raw')")
    check("~~ '%evil.com%'" in plan, "planner rewrite: wc_match(.., 'raw') becomes LIKE on a local table")

    # ---- Lake: Parquet files read by file(), pruned with the Puffin index
    os.makedirs(f"{work}/lake")
    schema = pa.schema([("id", pa.int64()), ("url", pa.string())])
    rows_by_file = []
    for f in range(8):
        # the security strings go to files 2 and 5 only; random traffic everywhere
        part = [(i, u) for i, u in enumerate(urls) if (i >= len(base) and i % 8 == f) or (i < len(base) and f == (2 if i < 5 else 5))]
        pq.write_table(pa.table({"id": [r[0] for r in part], "url": [r[1] for r in part]}, schema=schema), f"{work}/lake/f{f}.parquet")
        rows_by_file.append(part)
    ch_paths = sorted(ch("SELECT DISTINCT _path FROM file('lake/*.parquet', Parquet)").split())
    mapping = [f"{work}/lake/f{f}.parquet={next(p for p in ch_paths if p.endswith(f'f{f}.parquet'))}" for f in range(8)]
    sh(WC_LAKE, "index", "--column", "url", "--views", "raw,lower,decoded,revdomain", "--snapshot-id", "1", "--out", f"{work}/lk.puffin", *mapping)
    sh(WC_LAKE, "export-pg", f"{work}/lk.puffin", "--name", "lk", "--out-dir", f"{work}/lk")
    for t, f in [("wc_lake_index (index_name, column_name, views, snapshot_id)", "index"), ("wc_lake_file", "files"), ("wc_lake_gram", "grams")]:
        psql(f"\\copy {t} FROM '{work}/lk/{f}.csv' CSV")
    psql("CREATE FOREIGN TABLE lake_http (id bigint, url text) SERVER ch OPTIONS (table 'file(''lake/*.parquet'', Parquet)', lake_index 'lk')")
    psql("CREATE FOREIGN TABLE lake_full (id bigint, url text) SERVER ch OPTIONS (table 'file(''lake/*.parquet'', Parquet)')")
    lake_cases = ["wc_match(url, '*/wp-admin/*', 'decoded')", "wc_like(url, 'com.evil.%', 'revdomain')",
                  "wc_regex(url, 'powershell', true, 'lower')", "wc_match(url, '*/static/app.js', 'raw')"]
    for c in lake_cases:
        a = psql(f"SELECT coalesce(string_agg(id::text, ',' ORDER BY id), '') FROM lake_http WHERE {c}")
        b = psql(f"SELECT coalesce(string_agg(id::text, ',' ORDER BY id), '') FROM lake_full WHERE {c}")
        plan = psql(f"EXPLAIN (VERBOSE, COSTS OFF) SELECT id FROM lake_http WHERE {c}")
        files = [l.strip() for l in plan.split("\n") if "Lake files" in l]
        check(a == b and files and a != "", f"lake {c[:45]:45} rows={len(a.split(','))} identical={a == b} {files[0] if files else 'no pruning'}")
    for table in ["http_local", "http_plain", "http_candidate", "lake_http"]:
        try:
            psql(f"SELECT count(*) FROM {table} WHERE url LIKE " + r"E'abc\\'")
            check(False, f"dangling LIKE escape must still raise on {table}")
        except subprocess.CalledProcessError as error:
            check("escape" in error.stderr.lower(), f"dangling LIKE escape remains a PostgreSQL error on {table}")
    # prove skipping: truncate a file that is not a candidate for the wp-admin query
    victim = f"{work}/lake/f0.parquet"
    with open(victim, "r+b") as fh:
        fh.truncate(os.path.getsize(victim) // 2)
    ok_pruned = True
    try: psql("SELECT count(*) FROM lake_http WHERE wc_match(url, '*/wp-admin/*', 'decoded')")
    except subprocess.CalledProcessError: ok_pruned = False
    ok_full = True
    try: psql("SELECT count(*) FROM lake_full WHERE wc_match(url, '*/wp-admin/*', 'decoded')")
    except subprocess.CalledProcessError: ok_full = False
    check(ok_pruned and not ok_full, f"truncated non-candidate file: pruned query ok={ok_pruned}, full query ok={ok_full}")
except subprocess.CalledProcessError as e:
    print("ERROR:", e.stderr)
    failures += 1
finally:
    subprocess.run([f"{PGBIN}/pg_ctl", "-D", f"{work}/pg", "-m", "immediate", "stop"], capture_output=True)
    for p in procs:
        p.send_signal(signal.SIGTERM)
    shutil.rmtree(work, ignore_errors=True)

print("RESULT:", "PASS" if failures == 0 else f"FAIL ({failures})")
sys.exit(1 if failures else 0)
